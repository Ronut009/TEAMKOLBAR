# Moves the code into js/core, js/entities, js/levels, js/render and css/, and moves every file
# the game never loads into unused_assets/ (same sub-paths, nothing is deleted).
# Run it once from the game folder:  right-click > Run with PowerShell
$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot
$moved = 0; $skipped = 0
function Move-To([string]$src, [string]$dst) {
  if (-not (Test-Path -LiteralPath $src)) { $script:skipped++; return }
  if (Test-Path -LiteralPath $dst) { Write-Host "  already exists, left in place: $dst"; $script:skipped++; return }
  $dir = Split-Path -Parent $dst
  if ($dir -and -not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
  Move-Item -LiteralPath $src -Destination $dst
  $script:moved++
}

# Code files: the new copies already sit in js/core, js/entities, ... (written by Claude), so an old
# copy left at the old path is archived in unused_assets/superseded/ instead.
function Move-Code([string]$src, [string]$dst) {
  if (-not (Test-Path -LiteralPath $src)) { $script:skipped++; return }
  if (Test-Path -LiteralPath $dst) { Move-To $src ('unused_assets\superseded\' + $src); return }
  Move-To $src $dst
}

